import type { AssessmentResponse } from '@/interfaces/practice.interface';

/** Types of the in-app scorer (a port of backend/app/services/assessment_service.py). */

export type AlignmentOp = 'match' | 'substitution' | 'deletion' | 'insertion';
export type ScoreVerdict = 'ok' | 'check' | 'error';
export type VisualVerdict = 'ok' | 'off' | 'unavailable';

/** Frames × vocab log-softmax matrix, row-major. */
export interface PosteriorMatrix {
  frames: number;
  vocab: number;
  data: Float32Array;
}

export interface Phone {
  symbol: string;
  /** Vowels only: 0, 1 or 2. */
  stress: number | null;
}

export interface WordPronunciations {
  word: string;
  /** First variant is the dictionary's most common. */
  variants: Phone[][];
}

export interface ExpectedPhone {
  wordIndex: number;
  phone: Phone;
  isFinal: boolean;
}

export interface AlignedPair {
  op: AlignmentOp;
  expected: string;
  actual: string;
}

export interface PhoneSegment {
  symbol: string;
  startFrame: number;
  endFrame: number;
  gop: number;
}

export interface KnownError {
  id: string;
  expected: string;
  heard: string[];
  kind: AlignmentOp;
  priority: number;
  final_only?: boolean;
  viseme_group?: string | null;
  hint_vi: string;
  mouth_tip_vi?: string;
}

export interface VisemeGroupData {
  name_vi: string;
  sounds: string[];
  targets: Record<string, { min?: number; max?: number }>;
  hold_ms: number;
  hint_vi: string;
  common_error_vi: string;
  confidence?: string;
}

export interface PhoneInventory {
  classes: Record<string, string>;
  order: string[];
  ipa: Record<string, string>;
  unstressedIpa: Record<string, string>;
  espeak: Record<string, string[]>;
  espeakOrder: string[];
  nearest: Record<string, string[]>;
  diacritics: string[];
  toneDigits: string;
  unknown: string;
}

/** Everything the scorer reads besides the audio (generated by scripts/build_scoring_data.py). */
export interface ScoringData {
  vocab: Record<string, number>;
  lexicon: Record<string, string[][]>;
  errors: KnownError[];
  enabled: string[];
  visemes: { features: string[]; groups: Record<string, VisemeGroupData> };
  inventory: PhoneInventory;
}

/** Frame tracks at `hopSeconds`: f0 in Hz (NaN when unvoiced) and RMS energy. */
export interface ProsodyTracks {
  f0: Float64Array;
  rms: Float64Array;
  hopSeconds: number;
}

/** A vowel segment: its word, lexical stress and time span in seconds. */
export interface SyllableNucleus {
  wordIndex: number;
  stress: number;
  start: number;
  end: number;
}

export interface ProsodyFinding {
  aspect: 'word_stress' | 'final_contour' | 'rhythm';
  verdict: 'ok' | 'check';
  detail_vi: string;
  word_index: number | null;
}

export interface ScoringMouthFrame {
  t: number;
  features: Record<string, number>;
  quality: number;
}

/** One attempt: what the API's `/assess` form carries, with posteriors instead of audio. */
export interface LocalAssessmentInput {
  itemId: string;
  text: string;
  kind: string;
  posteriors: PosteriorMatrix;
  mouthFrames: ScoringMouthFrame[];
  audioStartedAt: number | null;
  modelVersion: string;
  /** 16 kHz mono audio of the take, for prosody; omitted → no prosody findings. */
  samples?: Float32Array;
}

/** Golden test data: posteriors packed to the columns the scorer reads. */
export interface PackedPosteriors {
  frames: number;
  vocab: number;
  columns: number[];
  values: string;
  argmax: string;
  argmaxValues: string;
}

export interface GoldenScoringCase {
  text: string;
  kind: string;
  itemId: string;
  audioStartedAt: number | null;
  enabledErrors: string[];
  mouthFrames: ScoringMouthFrame[];
  posteriors: PackedPosteriors;
  expected: Pick<AssessmentResponse, 'words' | 'summary'>;
}

/** Golden test data: a take with the server's pYIN tracks and prosody findings. */
export interface GoldenProsodyCase {
  text: string;
  kind: string;
  samples: string;
  f0: string;
  rms: string;
  words: string[];
  nuclei: SyllableNucleus[];
  prosody: { aspect: string; verdict: string; detail_vi: string; word_index: number | null }[];
}

/** Weekly plan inputs and outputs (dates are local `YYYY-MM-DD`). */
export interface SoundHistory {
  phoneme: string;
  total: number;
  ok: number;
  lastDay: string;
}

export interface RunDay {
  day: string;
  ok: number;
  check: number;
  error: number;
}

export interface DaySummary extends RunDay {
  runs: number;
}

export interface FocusPick {
  phoneme: string;
  reason: 'weak' | 'review' | 'new';
  total: number;
  okRate: number | null;
  daysSince: number | null;
}
